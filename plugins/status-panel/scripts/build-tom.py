#!/usr/bin/env python3
"""Turn a GIF into the panel's mascot assets: hooks/tom-assets.ts.

    python3 scripts/build-tom.py path/to/mascot.gif       # rewrite hooks/tom-assets.ts (the built-in mascot)
    python3 scripts/build-tom.py path/to/any.gif --json   # print the same assets as JSON (the panel's "Change mascot")
    python3 scripts/build-tom.py --emit-ts                # copy this script into hooks/build-tom-script.ts

The panel runs this script from hooks/build-tom-script.ts (fed to `python3 -`), so it works wherever the
plugin is installed. After editing this file, run it with --emit-ts to refresh that copy.

Needs ffmpeg. Writes, as base64 constants:
  TOM_GIF    the animation, shrunk to fit an Svg source (desktop, while working)
  TOM_STILL  its first frame as PNG (desktop, idle)
  TOM_RASTER half-block cell frames (terminal; any truecolor terminal)
"""
import base64, json, os, struct, subprocess, sys, tempfile

SVG_BUDGET = 120_000          # Svg source limit is 131072 chars; leave room for the wrapper
COLS, PIX_ROWS, FPS = 22, 16, 8  # terminal: 22 columns × 8 rows, 8 frames a second
DEFAULT = 0x01000000          # the terminal's own colour (lets near-black blend in)


def ff(*args: str) -> bytes:
    return subprocess.run(['ffmpeg', '-v', 'error', '-y', *args], check=True, capture_output=True).stdout


def shrunk_gif(src: str, tmp: str) -> tuple[bytes, int]:
    for width, colors, fps in [(140, 128, 15), (120, 96, 12), (100, 64, 12), (90, 48, 10), (72, 32, 8)]:
        out = os.path.join(tmp, f'{width}.gif')
        ff('-i', src, '-vf', f'fps={fps},scale={width}:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors={colors}[p];[b][p]paletteuse=dither=bayer', '-loop', '0', out)
        data = open(out, 'rb').read()
        if len(base64.b64encode(data)) <= SVG_BUDGET:
            return data, width
    sys.exit('GIF too large even at 72px wide; trim it first')


def size_of(png: bytes) -> tuple[int, int]:
    return struct.unpack('>II', png[16:24])


def raster_frames(src: str) -> list[str]:
    raw = ff('-i', src, '-vf', f'fps={FPS},scale={COLS}:{PIX_ROWS}:flags=area', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-')
    frame_len = COLS * PIX_ROWS * 3
    frames = []
    for f in range(len(raw) // frame_len):
        px = raw[f * frame_len:(f + 1) * frame_len]

        def color(x: int, y: int) -> int:
            r, g, b = px[(y * COLS + x) * 3:(y * COLS + x) * 3 + 3]
            return DEFAULT if r + g + b < 60 else (r << 16) | (g << 8) | b

        cells = b''.join(
            struct.pack('<III', 0x2580, color(x, 2 * row), color(x, 2 * row + 1))  # ▀: top pixel fg, bottom pixel bg
            for row in range(PIX_ROWS // 2) for x in range(COLS)
        )
        frames.append(base64.b64encode(cells).decode())
    return frames


def here() -> str:
    return os.path.dirname(os.path.abspath(__file__))  # only when run from the file, never via `python3 -`


def main() -> None:
    if sys.argv[1:] == ['--emit-ts']:
        target = os.path.join(here(), '..', 'hooks', 'build-tom-script.ts')
        with open(os.path.abspath(__file__)) as fh:
            source = fh.read()
        with open(target, 'w') as fh:
            fh.write('// Generated by `python3 scripts/build-tom.py --emit-ts`: the converter the panel feeds to `python3 -`.\n')
            fh.write(f'export const BUILD_TOM_PY: string = {json.dumps(source)}\n')
        print(f'wrote {os.path.normpath(target)}')
        return
    src = sys.argv[1]
    as_json = '--json' in sys.argv[2:]
    with tempfile.TemporaryDirectory() as tmp:
        gif, width = shrunk_gif(src, tmp)
        still_path = os.path.join(tmp, 'still.png')
        ff('-i', src, '-vframes', '1', '-vf', f'scale={width}:-1:flags=lanczos', still_path)
        still = open(still_path, 'rb').read()
    w, h = size_of(still)
    frames = raster_frames(src)
    if as_json:
        print(json.dumps({
            'gif': base64.b64encode(gif).decode(), 'still': base64.b64encode(still).decode(), 'width': w, 'height': h,
            'raster': {'columns': COLS, 'rows': PIX_ROWS // 2, 'frameMs': 1000 // FPS, 'frames': frames},
        }))
        return
    out = os.path.join(here(), '..', 'hooks', 'tom-assets.ts')
    with open(out, 'w') as fh:
        fh.write(f'// Generated by scripts/build-tom.py from {os.path.basename(src)}; rerun it instead of editing.\n')
        fh.write(f'export const TOM_SIZE = {{ width: {w}, height: {h} }} as const\n')
        fh.write(f"export const TOM_GIF = '{base64.b64encode(gif).decode()}'\n")
        fh.write(f"export const TOM_STILL = '{base64.b64encode(still).decode()}'\n")
        fh.write(f'export const TOM_RASTER = {{\n  columns: {COLS},\n  rows: {PIX_ROWS // 2},\n  frameMs: {1000 // FPS},\n  frames: [\n')
        fh.writelines(f"    '{fr}',\n" for fr in frames)
        fh.write('  ],\n}\n')
    print(f'gif {len(gif) // 1024}KB at {w}x{h}, still {len(still) // 1024}KB, {len(frames)} terminal frames -> {os.path.normpath(out)}')


if __name__ == '__main__':
    main()
